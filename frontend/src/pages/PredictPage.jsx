import React, { useEffect, useState } from 'react'
import { predictSalary, getFeatures } from '../services/api'
import { fmtNum } from '../services/utils'

function fmtAmt(value) {
  if (value == null || isNaN(value)) return '—'
  return Number(value).toLocaleString('en-US', { minimumFractionDigits: 2, maximumFractionDigits: 2 })
}

const INIT_FORM = {
  Education: '',
  Experience: '',
  Location: '',
  Job_Title: '',
  Age: '',
  Gender: '',
}

export default function PredictPage() {
  const [features, setFeatures] = useState(null)
  const [form, setForm] = useState(INIT_FORM)
  const [result, setResult] = useState(null)
  const [loading, setLoading] = useState(false)
  const [fetchingFeatures, setFetchingFeatures] = useState(true)
  const [errors, setErrors] = useState({})
  const [apiError, setApiError] = useState(null)

  useEffect(() => {
    getFeatures()
      .then(r => setFeatures(r.data))
      .catch(() => setApiError('Failed to load feature options from the server.'))
      .finally(() => setFetchingFeatures(false))
  }, [])

  const validate = () => {
    const errs = {}
    if (!form.Education) errs.Education = 'Required'
    if (!form.Location)  errs.Location  = 'Required'
    if (!form.Job_Title) errs.Job_Title = 'Required'
    if (!form.Gender)    errs.Gender    = 'Required'
    const exp = parseFloat(form.Experience)
    if (isNaN(exp) || exp < 0 || exp > 50) errs.Experience = 'Must be 0–50'
    const age = parseInt(form.Age, 10)
    if (isNaN(age) || age < 18 || age > 80) errs.Age = 'Must be 18–80'
    setErrors(errs)
    return Object.keys(errs).length === 0
  }

  const handleChange = e => {
    setForm(f => ({ ...f, [e.target.name]: e.target.value }))
    setErrors(prev => ({ ...prev, [e.target.name]: undefined }))
  }

  const handleSubmit = async e => {
    e.preventDefault()
    if (!validate()) return
    setLoading(true)
    setApiError(null)
    setResult(null)
    try {
      const payload = {
        ...form,
        Experience: parseFloat(form.Experience),
        Age: parseInt(form.Age, 10),
      }
      const { data } = await predictSalary(payload)
      setResult(data)
    } catch (err) {
      const msg = err.response?.data?.detail || err.message
      setApiError(typeof msg === 'string' ? msg : JSON.stringify(msg))
    } finally {
      setLoading(false)
    }
  }

  if (fetchingFeatures) return (
    <div className="loading-overlay">
      <div className="spinner" style={{ borderTopColor: 'var(--ibm-blue)', borderColor: '#c6c6c6' }} />
      <span>Loading options…</span>
    </div>
  )


  return (
    <div style={{ maxWidth: 860 }}>
      <div className="card" style={{ marginBottom: 24 }}>
        <div style={{ marginBottom: 20 }}>
          <h3 style={{ fontSize: 16, fontWeight: 700, marginBottom: 4 }}>Salary Prediction Form</h3>
          <p style={{ fontSize: 13, color: 'var(--text-muted)' }}>
            Enter employee / job information to receive an ML-based salary prediction.
            The prediction is generated by the trained model — never hardcoded.
          </p>
        </div>

        <form onSubmit={handleSubmit}>
          <div className="form-grid">

            {/* Education */}
            <div className="form-field">
              <label>Education *</label>
              <select name="Education" value={form.Education} onChange={handleChange}>
                <option value="">Select…</option>
                {(features?.Education || []).map(v => <option key={v} value={v}>{v}</option>)}
              </select>
              {errors.Education && <div style={{ color: 'var(--ibm-red)', fontSize: 11, marginTop: 3 }}>{errors.Education}</div>}
            </div>

            {/* Experience */}
            <div className="form-field">
              <label>Experience (years) *</label>
              <input
                type="number" name="Experience"
                value={form.Experience} onChange={handleChange}
                min={features?.Experience_range?.min ?? 0}
                max={features?.Experience_range?.max ?? 50}
                step="0.5" placeholder="e.g. 5"
              />
              {errors.Experience && <div style={{ color: 'var(--ibm-red)', fontSize: 11, marginTop: 3 }}>{errors.Experience}</div>}
            </div>

            {/* Location */}
            <div className="form-field">
              <label>Location *</label>
              <select name="Location" value={form.Location} onChange={handleChange}>
                <option value="">Select…</option>
                {(features?.Location || []).map(v => <option key={v} value={v}>{v}</option>)}
              </select>
              {errors.Location && <div style={{ color: 'var(--ibm-red)', fontSize: 11, marginTop: 3 }}>{errors.Location}</div>}
            </div>

            {/* Job Title */}
            <div className="form-field">
              <label>Job Title *</label>
              <select name="Job_Title" value={form.Job_Title} onChange={handleChange}>
                <option value="">Select…</option>
                {(features?.Job_Title || []).map(v => <option key={v} value={v}>{v}</option>)}
              </select>
              {errors.Job_Title && <div style={{ color: 'var(--ibm-red)', fontSize: 11, marginTop: 3 }}>{errors.Job_Title}</div>}
            </div>

            {/* Age */}
            <div className="form-field">
              <label>Age *</label>
              <input
                type="number" name="Age"
                value={form.Age} onChange={handleChange}
                min={features?.Age_range?.min ?? 18}
                max={features?.Age_range?.max ?? 80}
                step="1" placeholder="e.g. 28"
              />
              {errors.Age && <div style={{ color: 'var(--ibm-red)', fontSize: 11, marginTop: 3 }}>{errors.Age}</div>}
            </div>

            {/* Gender */}
            <div className="form-field">
              <label>Gender *</label>
              <select name="Gender" value={form.Gender} onChange={handleChange}>
                <option value="">Select…</option>
                {(features?.Gender || []).map(v => <option key={v} value={v}>{v}</option>)}
              </select>
              {errors.Gender && <div style={{ color: 'var(--ibm-red)', fontSize: 11, marginTop: 3 }}>{errors.Gender}</div>}
            </div>

          </div>

          <div style={{ marginTop: 24, display: 'flex', alignItems: 'center', gap: 16 }}>
            <button type="submit" className="btn btn-primary" disabled={loading}>
              {loading ? (
                <span style={{ display: 'flex', alignItems: 'center', gap: 8 }}>
                  <span className="spinner" />
                  Predicting…
                </span>
              ) : 'Predict Salary'}
            </button>
            <button type="button" className="btn btn-secondary"
              onClick={() => { setForm(INIT_FORM); setResult(null); setApiError(null); }}>
              Reset
            </button>
          </div>
        </form>

        {apiError && <div className="error-msg" style={{ marginTop: 16 }}>{apiError}</div>}
      </div>

      {/* ── Prediction Result ──────────────────────────────────────────── */}
      {result && (
        <div className="prediction-result">
          <div className="label">Predicted Annual Salary</div>
          <div className="main-salary">{fmtAmt(result.predicted_salary)}</div>

          {result.lower_bound != null && result.upper_bound != null && (
            <div className="range-text">
              Estimated range (90 % interval): {fmtAmt(result.lower_bound)} — {fmtAmt(result.upper_bound)}
              <span style={{ fontSize: 11, opacity: .7, marginLeft: 8 }}>
                (based on model RMSE — statistical estimate only)
              </span>
            </div>
          )}

          <div style={{ fontSize: 13, opacity: .85, marginBottom: 16 }}>
            Monthly equivalent: {fmtAmt(result.predicted_salary / 12)}
          </div>

          <div className="meta-grid">
            <div className="meta-item">
              <div className="key">Prediction Engine</div>
              <div className="val">{result.prediction_engine}</div>
            </div>
            <div className="meta-item">
              <div className="key">Model</div>
              <div className="val">{result.model_name}</div>
            </div>
            <div className="meta-item">
              <div className="key">Model Version</div>
              <div className="val">{result.model_version}</div>
            </div>
            <div className="meta-item">
              <div className="key">Currency</div>
              <div className="val">{result.currency} ({result.currency_symbol})</div>
            </div>
          </div>

          {/* Input Summary */}
          <div style={{ marginTop: 20, borderTop: '1px solid rgba(255,255,255,.25)', paddingTop: 16 }}>
            <div style={{ fontSize: 12, opacity: .7, marginBottom: 8, textTransform: 'uppercase', letterSpacing: '.05em' }}>
              Input Summary
            </div>
            <div style={{ display: 'flex', flexWrap: 'wrap', gap: '8px 24px' }}>
              {Object.entries(result.input_summary).map(([k, v]) => (
                <span key={k} style={{ fontSize: 13 }}>
                  <span style={{ opacity: .7 }}>{k.replace('_', ' ')}: </span>
                  <strong>{v}</strong>
                </span>
              ))}
            </div>
          </div>
        </div>
      )}

      {/* Fairness notice */}
      <div className="card" style={{ marginTop: 20, borderLeft: '3px solid var(--ibm-orange)', fontSize: 12, color: 'var(--text-muted)' }}>
        <strong>Note on Gender feature:</strong> Gender is included as a statistical input feature
        based on its presence in the dataset. The model makes no causal claims about gender and salary.
        Salary distributions by gender are shown under Analytics as observed dataset distributions only.
        This tool should not be used to make employment decisions automatically.
      </div>
    </div>
  )
}
